export type ThinkingLevel = 'off' | 'minimal' | 'low' | 'medium' | 'high';

export interface ProviderDefinition {
  id: string;
  name: string;
  badge?: string;
  description: string;
  defaultBaseUrl: string;
  envKeyName?: string;
  isLocal?: boolean;
  requiresBaseUrl?: boolean;
  defaultModel?: string;
  modelPlaceholder?: string;
  authHeaderType?: 'bearer' | 'api-key' | 'none';
  docUrl?: string;
}

export interface StoredProviderConfig {
  id: string;
  apiKey?: string;
  baseUrl?: string;
  configured: boolean;
  selectedModel?: string;
  cachedModels?: Array<{ id: string; name?: string; description?: string }>;
  thinkingLevel?: ThinkingLevel;
  updatedAt?: number;
  verifiedAt?: number;
}

export interface IntermediateModelSettings {
  enabled: boolean;
  providerId: string;
  modelId: string;
  thinkingLevel: ThinkingLevel;
  customBaseUrl?: string;
  updatedAt?: number;
}

export interface ProviderStatusSummary {
  id: string;
  name: string;
  configured: boolean;
  maskedKey: string | null;
  baseUrl: string;
  selectedModel: string;
  cachedModelsCount: number;
  cachedModels: Array<{ id: string; name?: string }>;
  thinkingLevel: ThinkingLevel;
  isLocal?: boolean;
  updatedAt?: number;
  verifiedAt?: number;
}

export interface TestProviderResult {
  valid: boolean;
  latencyMs: number;
  modelCount?: number;
  statusCode?: number;
  errorCode?: string;
  message?: string;
  error?: string;
}

